import assert from 'node:assert/strict';
import {validateMutation} from '../src/lib/member/validation.mjs';
import {snapshotPractice,restorePractice} from '../src/lib/member/practice.mjs';
const item={path:'/learn/pharmacy/modules/example',type:'module',sections:['one','two']};
assert.deepEqual(validateMutation({path:item.path,action:'save',data:{saved:true}},item),{saved:true});
assert.throws(()=>validateMutation({path:'/other',action:'save',data:{saved:true}},item));
assert.throws(()=>validateMutation({path:item.path,action:'progress',data:{section:'invented'}},item));
assert.throws(()=>validateMutation({path:item.path,action:'note',data:{section:'',text:'x'.repeat(5001)}},item));
assert.throws(()=>validateMutation({path:item.path,action:'practice',data:{id:'quiz',state:{long:'x'.repeat(60001)}}},item));
const qs=[{id:'a',question:'Q',choices:['A','B','C'],answer:1,explanation:'Why'}];
const shuffled=[{...qs[0],choices:['B','C','A'],answer:0}];
const snapshot=snapshotPractice(qs,shuffled,{a:0},false,1,'a');
const resumed=restorePractice(qs,JSON.parse(JSON.stringify(snapshot)));
assert.deepEqual(resumed.attempt,shuffled);assert.equal(resumed.answers.a,0);assert.equal(resumed.submitted,false);
assert.equal(restorePractice([{...qs[0],answer:2}],snapshot),null,'Changed content invalidates saved practice');
assert.equal(restorePractice(qs,{...snapshot,order:[{id:'a',choices:['B','B','A']}]}),null);
assert.equal(restorePractice(qs,{...snapshot,answers:{a:99}}),null);
assert.equal(restorePractice(qs,{...snapshot,answers:{},submitted:true}).submitted,false);
console.log('Member validation and randomized practice resume tests passed.');
