import assert from 'node:assert/strict';
import {rankResources,groundLinks,requestedDestination} from '../src/lib/nicole/discovery.mjs';
import {publicSearchIndex} from '../src/lib/site-search/catalog.mjs';
import {PUBLIC_STUDIO_ORGANS} from '../src/lib/anatomy-studio/public-registry.mjs';
import {learningVideos,videoWatchUrl} from '../src/data/learningVideos.js';
const catalog=publicSearchIndex.map(row=>({...row,path:row.href,keywords:row.searchText}));
const models=PUBLIC_STUDIO_ORGANS.map(row=>({title:row.label+' model',path:'/learn/anatomy?model='+row.id,category:'Model'}));
const videos=learningVideos.map(video=>({title:video.title,path:videoWatchUrl(video.id),category:'Video',description:video.description}));
const resources=[...catalog,...models,...videos];
const matches=rankResources(resources,'Do you have any NaS resources I can use to study cardiology?');
assert.match(matches[0].title,/cardiac|cardiovascular|heart/i);
assert(!matches.some(row=>/account|admin|preview/.test(row.path)));
const heart=models.find(row=>row.path.endsWith('=heart'));
assert.equal(requestedDestination('Open the '+heart.title,rankResources(resources,'Open the '+heart.title)),heart.path);
assert.equal(requestedDestination('Open the heart model or brain model',[heart,...models]),null);
assert.equal(requestedDestination('Open the heart model',[heart,{...heart,path:'/learn/duplicate'}]),null);
assert.equal(requestedDestination('Explain the '+heart.title,[heart]),null);
assert.equal(requestedDestination('Open my admin dashboard',[heart]),null);
assert.equal(groundLinks('[Invented](/private) and [Heart]('+heart.path+')',[heart]),'Invented and [Heart]('+heart.path+')');
assert(videos.length>0);
const fresh={title:'New cardiovascular film',category:'Video',description:'heart pressure',path:videoWatchUrl('abcdefghijk'),passages:['Transcript passage about ventricular waveforms']};
assert(rankResources([...resources,fresh],'ventricular waveforms video').some(row=>row.path===fresh.path&&row.excerpt.includes('waveforms')));
console.log('Catalog discovery, verified links, explicit navigation and updated video transcript fixture passed.',matches.map(row=>row.title));
