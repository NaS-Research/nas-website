import assert from "node:assert/strict";
import { validateDrugRequest } from "../src/lib/drugRequest.mjs";
import guard, { config } from "../netlify/edge-functions/drug-api-guard.js";
const req = (q, headers = {}) => new Request(`https://nasresearch.bio/api/drugs/search?${q}`, { headers });
assert.equal(validateDrugRequest(req("q=aspirin"), "q", 80).value, "aspirin");
assert.equal(validateDrugRequest(req("q=a&q=b"), "q", 80).status, 400);
assert.equal(validateDrugRequest(req("q=" + "x".repeat(81)), "q", 80).status, 400);
assert.equal(validateDrugRequest(req("q=asp%00irin"), "q", 80).status, 400);
assert.equal(validateDrugRequest(req("q=aspirin", {"sec-fetch-site":"cross-site"}), "q", 80).status, 403);
assert.equal(validateDrugRequest(req("q=aspirin", {"sec-fetch-site":"same-origin"}), "q", 80).value, "aspirin");
let calls = 0;
const context = { next: () => { calls++; return new Response("ok"); } };
assert.equal((await guard(new Request("https://nasresearch.bio/api/drugs/search", { method:"POST" }), context)).status, 405);
assert.equal(calls, 0);
assert.equal((await guard(req("q=" + "x".repeat(513)), context)).status, 414);
assert.equal(calls, 0);
assert.equal((await guard(req("q=aspirin"), context)).status, 200);
assert.equal(calls, 1);
assert.deepEqual(config.rateLimit.aggregateBy, ["ip", "domain"]);
console.log("Security request tests passed");
